-- 곡에 가사를 붙여 둔다.
--
-- ── 왜
--
-- 보관함에서 지난 곡을 다시 「함께 부르기」로 열 수가 없었다. 재생은 되는데
-- 화면에 띄울 가사가 없어서다. 가사는 회기 상태(localStorage)에만 있었고,
-- 회기가 끝나면 사라진다.
--
-- 노래방 화면은 가사가 있어야 성립한다. 어르신이 지난달에 만든 노래를 다시
-- 부르시려면 그 곡의 가사가 곡을 따라다녀야 한다.
--
-- ── 왜 lyrics 표를 안 쓰나
--
-- lyrics 표는 회기에 매여 있다(session_id). 그런데 곡의 임자는 회기가 아니라
-- 어르신이고(songs.session_id 는 비어 있을 수 있다), 기기에서 만든 곡은
-- 회기 행과 못 잇는 경우가 있다. 곡과 함께 다녀야 하는 값이라 곡 옆에 둔다.
--
-- 지금 있는 곡들은 이 칸이 비어 있다. 화면은 가사가 있는 곡에만 「함께
-- 부르기」를 띄운다 — 없는 것을 있는 척하지 않는다.

alter table songs add column if not exists lyrics jsonb;

comment on column songs.lyrics is
  '가사 절 배열 [{label,tone,lines[]}]. 보관함에서 다시 함께 부르기 위해 곡에 붙여 둔다.';
